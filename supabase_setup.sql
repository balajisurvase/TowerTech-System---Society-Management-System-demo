-- 7. Security Table
CREATE TABLE IF NOT EXISTS security (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    security_id TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    phone TEXT,
    mobile_number TEXT,
    password TEXT NOT NULL,
    society_id TEXT DEFAULT 'GV2026',
