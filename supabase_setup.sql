);

-- 8. Visitors Table (Standardized plural name & auto-generated BIGINT identity visitor_id)
CREATE TABLE IF NOT EXISTS visitors (
    visitor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id UUID DEFAULT gen_random_uuid(),
    visitor_name TEXT NOT NULL,
    visitor_mobile TEXT NOT NULL,
    visitor_type TEXT DEFAULT 'Guest',
    category TEXT DEFAULT 'guest',
    vehicle_number TEXT,
    profile_photo TEXT,
    resident_id TEXT NOT NULL,
    resident_name TEXT,
    tower TEXT,
    floor INTEGER,
    flat TEXT,
    purpose TEXT NOT NULL,
    gate TEXT DEFAULT 'Main Gate',
    visitor_count INTEGER DEFAULT 1,
    expected_duration TEXT,
    rejection_reason TEXT,
    status TEXT DEFAULT 'pending', -- pending, approved, rejected, inside, exited, cancelled
    approval_status TEXT DEFAULT 'pending', -- pending, approved, rejected
    approval_time TIMESTAMP WITH TIME ZONE,
    approved_by TEXT,
    rejected_time TIMESTAMP WITH TIME ZONE,
    rejected_by TEXT,
    entry_time TIMESTAMP WITH TIME ZONE,
    checked_in_by TEXT,
    exit_time TIMESTAMP WITH TIME ZONE,
    checked_out_by TEXT,
    security_id TEXT,
    security_user_name TEXT,
    security_user_mobile TEXT,
    security_user_shift TEXT,
    society_id TEXT DEFAULT 'GV2026',
    is_invitation BOOLEAN DEFAULT false,
    invitation_code TEXT,
    valid_until TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

