-- Safe migration from legacy 'visitor' (singular) table if it exists
DO $$
BEGIN
  IF EXISTS (SELECT FROM pg_tables WHERE schemaname = 'public' AND tablename = 'visitor') THEN
    INSERT INTO visitors (
      visitor_name, visitor_mobile, visitor_type, vehicle_number, profile_photo,
      resident_id, resident_name, tower, floor, flat, purpose, gate,
      visitor_count, rejection_reason, status, approval_status, approval_time,
      security_id, security_user_name, security_user_shift, society_id, created_at
    )
    SELECT 
      visitor_name, visitor_mobile, COALESCE(visitor_type, 'Guest'), vehicle_number, profile_photo,
      resident_id, resident_name, tower, floor, flat, purpose, COALESCE(gate, 'Main Gate'),
      COALESCE(visitor_count, 1), rejection_reason, LOWER(COALESCE(status, 'pending')), LOWER(COALESCE(approval_status, 'pending')), approval_time,
      security_id, security_user_name, security_user_shift, COALESCE(society_id, 'GV2026'), COALESCE(created_at, NOW())
    FROM visitor
    ON CONFLICT DO NOTHING;
  END IF;
END $$;

